use std::collections::HashMap;
use std::fs;
use std::path::Path;
use tracing::info;

#[derive(Debug, Clone)]
pub struct ServerConfig {
    pub server_ip: String,
    pub server_port: u16,
    pub motd: String,
    pub max_players: i32,
    pub online_mode: bool,
    pub view_distance: u32,
    pub simulation_distance: u32,
    pub enable_status: bool,
    pub network_compression_threshold: i32,
    pub pvp: bool,
    pub difficulty: String,
    pub gamemode: String,
    pub white_list: bool,
    pub target_version: String,
    pub multi_version: bool,
    pub raw_properties: HashMap<String, String>,
}

impl Default for ServerConfig {
    fn default() -> Self {
        Self {
            server_ip: "0.0.0.0".to_string(),
            server_port: 25565,
            motd: "§bA CrabMC Minecraft Server §7(Rust Powered)".to_string(),
            max_players: 20,
            online_mode: false,
            view_distance: 10,
            simulation_distance: 10,
            enable_status: true,
            network_compression_threshold: 256,
            pvp: true,
            difficulty: "easy".to_string(),
            gamemode: "survival".to_string(),
            white_list: false,
            target_version: "1.21.1".to_string(),
            multi_version: true,
            raw_properties: HashMap::new(),
        }
    }
}

impl ServerConfig {
    pub fn load_or_create<P: AsRef<Path>>(path: P) -> anyhow::Result<Self> {
        let path = path.as_ref();
        if !path.exists() {
            info!("No server.properties found. Generating default server.properties...");
            let default_cfg = ServerConfig::default();
            default_cfg.save_to_file(path)?;
            return Ok(default_cfg);
        }

        info!("Loading configuration from {}", path.display());
        let content = fs::read_to_string(path)?;
        let mut map = HashMap::new();

        for line in content.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') || line.starts_with('!') {
                continue;
            }

            if let Some((k, v)) = line.split_once('=') {
                map.insert(k.trim().to_string(), v.trim().to_string());
            }
        }

        let mut config = ServerConfig::default();

        if let Some(ip) = map.get("server-ip") {
            if !ip.is_empty() {
                config.server_ip = ip.clone();
            }
        }
        if let Some(port) = map.get("server-port").and_then(|p| p.parse().ok()) {
            config.server_port = port;
        }
        if let Some(motd) = map.get("motd") {
            config.motd = motd.clone();
        }
        if let Some(max) = map.get("max-players").and_then(|p| p.parse().ok()) {
            config.max_players = max;
        }
        if let Some(online) = map.get("online-mode").and_then(|p| p.parse().ok()) {
            config.online_mode = online;
        }
        if let Some(vd) = map.get("view-distance").and_then(|p| p.parse().ok()) {
            config.view_distance = vd;
        }
        if let Some(sd) = map.get("simulation-distance").and_then(|p| p.parse().ok()) {
            config.simulation_distance = sd;
        }
        if let Some(status) = map.get("enable-status").and_then(|p| p.parse().ok()) {
            config.enable_status = status;
        }
        if let Some(comp) = map.get("network-compression-threshold").and_then(|p| p.parse().ok()) {
            config.network_compression_threshold = comp;
        }
        if let Some(pvp) = map.get("pvp").and_then(|p| p.parse().ok()) {
            config.pvp = pvp;
        }
        if let Some(diff) = map.get("difficulty") {
            config.difficulty = diff.clone();
        }
        if let Some(gm) = map.get("gamemode") {
            config.gamemode = gm.clone();
        }
        if let Some(wl) = map.get("white-list").and_then(|p| p.parse().ok()) {
            config.white_list = wl;
        }
        if let Some(target_ver) = map.get("target-version") {
            config.target_version = target_ver.clone();
        }
        if let Some(multi_ver) = map.get("multi-version").and_then(|p| p.parse().ok()) {
            config.multi_version = multi_ver;
        }

        config.raw_properties = map;
        Ok(config)
    }

    pub fn save_to_file<P: AsRef<Path>>(&self, path: P) -> anyhow::Result<()> {
        let content = format!(
            r#"# Minecraft server properties
# Auto-generated by CrabMC (Rust)
# https://github.com/myzert/crabmc-server
server-ip={}
server-port={}
motd={}
max-players={}
online-mode={}
view-distance={}
simulation-distance={}
enable-status={}
network-compression-threshold={}
pvp={}
difficulty={}
gamemode={}
white-list={}
target-version={}
multi-version={}
"#,
            self.server_ip,
            self.server_port,
            self.motd,
            self.max_players,
            self.online_mode,
            self.view_distance,
            self.simulation_distance,
            self.enable_status,
            self.network_compression_threshold,
            self.pvp,
            self.difficulty,
            self.gamemode,
            self.white_list,
            self.target_version,
            self.multi_version
        );

        fs::write(path, content)?;
        Ok(())
    }
}
